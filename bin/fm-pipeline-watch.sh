#!/usr/bin/env bash
# fm-pipeline-watch.sh - watch the standing health of Amazon pipelines,
# independent of any task.
#
# Usage:
#   fm-pipeline-watch.sh arm                 arm one check per pipeline in config/watched-pipelines
#                                            and disarm watches for pipelines no longer listed
#   fm-pipeline-watch.sh poll <pipeline>     one health read; the armed check runs this
#   fm-pipeline-watch.sh disarm [<pipeline>] remove one watch, or every watch with no argument
#   fm-pipeline-watch.sh --help              print this help
#
# config/watched-pipelines lists one pipeline name per line; blank lines and
# lines starting with # are ignored. Each listed pipeline gets
# state/pw-<pipeline>.check.sh, bound with fm-check-register.sh, so the watcher
# runs it on its FM_CHECK_INTERVAL sweep and turns its one line into a check
# wake. Each poll prints a line only when firstmate should wake:
#   pipeline-failing: <pipeline> <current failures> <url>  a failure not seen last poll
#   pipeline-recovered: <pipeline> <url>                   the last failure cleared
#   pipeline-watch-stale: <pipeline> <reason> <url>        the read failed (at most hourly)
# where <url> is https://pipelines.amazon.com/pipelines/<pipeline>.
#
# A failure is a failed build, deployment, or test step, or a blocked promotion
# whose blocker is not a TIME_WINDOW. Each failure is keyed by its step url (or
# its promotion id and blocker name), so the same failure never wakes twice, a
# partial clear stays quiet, and a new failure on an already-red pipeline does
# wake. A failed read (missing builder CLI, builder error, non-zero exit,
# timeout, unparsable JSON) keeps the last failure set, so it is never reported
# as healthy or recovered. state/pw-<pipeline>.seen holds that set and the time
# of the last stale line.
#
# The read is builder-mcp's GetPipelineDetails, called through
# fm-builder-mcp-call.sh, which uses builder-mcp's own Midway session.
# Environment:
#   FM_PIPELINE_WATCH_BUILDER     builder CLI called as `<cli> GetPipelineDetails <json>`
#                                 (default: fm-builder-mcp-call.sh); a value set
#                                 at arm time becomes the check's default
#   FM_PIPELINE_WATCH_TIMEOUT     seconds allowed per read (default 20); keep it
#                                 under the watcher's FM_CHECK_TIMEOUT (default 30)
#   FM_PIPELINE_WATCH_STALE_SECS  minimum seconds between stale lines (default 3600)
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
CONFIG="${FM_CONFIG_OVERRIDE:-$FM_HOME/config}/watched-pipelines"

# shellcheck source=bin/fm-timeout-lib.sh
. "$SCRIPT_DIR/fm-timeout-lib.sh"
# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

usage() {
  sed -n '3,10s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"
}

die_usage() {
  echo "usage: fm-pipeline-watch.sh arm | poll <pipeline> | disarm [<pipeline>]" >&2
  exit 1
}

# The name lands in a file name, the generated check, and a JSON payload.
pipeline_valid() {
  case "$1" in
    ''|.*|*[!A-Za-z0-9._-]*) return 1 ;;
  esac
}

require_pipeline() {
  pipeline_valid "$1" || {
    echo "error: pipeline '$1' must match [A-Za-z0-9._-]+ and not start with a dot" >&2
    exit 1
  }
}

# configured_pipelines: the valid names in config/watched-pipelines, one per
# line. Fails naming the first invalid line, so a typo never arms a partial set.
configured_pipelines() {
  local line name
  while IFS= read -r line || [ -n "$line" ]; do
    name=$(printf '%s' "$line" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    case "$name" in ''|'#'*) continue ;; esac
    pipeline_valid "$name" || {
      echo "error: $CONFIG lists an invalid pipeline name '$name'" >&2
      return 1
    }
    printf '%s\n' "$name"
  done < "$CONFIG"
}

armed_pipelines() {
  local c name
  for c in "$STATE"/pw-*.check.sh; do
    [ -e "$c" ] || continue
    name=${c##*/pw-}
    printf '%s\n' "${name%.check.sh}"
  done
}

shim_content() {
  local pipeline=$1 builder_line=
  [ -n "${FM_PIPELINE_WATCH_BUILDER:-}" ] &&
    builder_line="export FM_PIPELINE_WATCH_BUILDER=\${FM_PIPELINE_WATCH_BUILDER:-$(printf '%q' "$FM_PIPELINE_WATCH_BUILDER")}"
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    "# Generated by fm-pipeline-watch.sh arm - standing health poll for $pipeline." \
    "export FM_STATE_OVERRIDE=$(printf '%q' "$STATE")"
  [ -z "$builder_line" ] || printf '%s\n' "$builder_line"
  printf '%s\n' "exec $(printf '%q' "$SCRIPT_DIR/fm-pipeline-watch.sh") poll $pipeline"
}

# arm_one <pipeline>: write and bind state/pw-<pipeline>.check.sh. A failed
# bind removes the check, because the watcher rejects an unbound check on every
# sweep.
arm_one() {
  local pipeline=$1 id shim want device tmp
  id="pw-$pipeline"
  shim="$STATE/$id.check.sh"
  want=$(shim_content "$pipeline")
  if [ -f "$shim" ] && [ "$(cat "$shim")" = "$want" ] \
    && fm_custom_check_registered "$STATE" "$id"; then
    echo "armed: state/$id.check.sh watches https://pipelines.amazon.com/pipelines/$pipeline"
    return 0
  fi
  device=$(fm_pr_file_device "$STATE") || return 1
  fm_pr_regular_destination_on_device_or_absent "$shim" "$device" || {
    echo "error: state/$id.check.sh is not a regular file" >&2
    return 1
  }
  tmp=$(umask 077; mktemp "$STATE/.fm-pipeline-watch.XXXXXX") || return 1
  if ! printf '%s\n' "$want" > "$tmp" || ! chmod 0700 "$tmp" || ! mv -f -- "$tmp" "$shim"; then
    rm -f -- "$tmp"
    echo "error: could not write state/$id.check.sh" >&2
    return 1
  fi
  if ! FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-register.sh" "$id" >/dev/null; then
    FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-unregister.sh" "$id" >/dev/null 2>&1 \
      || rm -f -- "$shim"
    echo "error: could not register state/$id.check.sh" >&2
    return 1
  fi
  echo "armed: state/$id.check.sh watches https://pipelines.amazon.com/pipelines/$pipeline"
}

disarm_one() {
  local id="pw-$1"
  FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-unregister.sh" "$id" >/dev/null || return 1
  rm -f -- "$STATE/$id.seen" "$STATE/$id.seen".*
  echo "disarmed: pipeline watch for $1"
}

action_arm() {
  local wanted name rc=0
  [ -f "$CONFIG" ] || { echo "error: no pipeline list at $CONFIG" >&2; return 1; }
  wanted=$(configured_pipelines) || return 1
  [ -n "$wanted" ] || { echo "error: $CONFIG lists no pipelines" >&2; return 1; }
  mkdir -p "$STATE" || return 1
  while IFS= read -r name; do
    arm_one "$name" || rc=1
  done <<EOF
$wanted
EOF
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    printf '%s\n' "$wanted" | grep -qxF -- "$name" && continue
    disarm_one "$name" || rc=1
  done <<EOF
$(armed_pipelines)
EOF
  return "$rc"
}

action_disarm() {
  local name rc=0
  if [ -n "${1:-}" ]; then
    require_pipeline "$1"
    disarm_one "$1"
    return
  fi
  [ -d "$STATE" ] || return 0
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    disarm_one "$name" || rc=1
  done <<EOF
$(armed_pipelines)
EOF
  return "$rc"
}

# write_seen <stale_at> <keys>: atomically record the stale clock and failure keys.
write_seen() {
  local tmp
  tmp=$(mktemp "$SEEN.XXXXXX") || return 1
  {
    printf 'stale_at=%s\n' "$1"
    [ -z "$2" ] || printf '%s\n' "$2" | sed 's/^/key=/'
  } > "$tmp"
  mv -f -- "$tmp" "$SEEN"
}

seen_keys() {
  [ ! -f "$SEEN" ] || sed -n 's/^key=//p' "$SEEN"
}

# seen_stale_at: epoch of the last stale line, or 0. A good read keeps it, so the
# hourly bound also holds for a read that flaps between success and failure.
seen_stale_at() {
  local stale_at=
  [ ! -f "$SEEN" ] || stale_at=$(sed -n 's/^stale_at=//p' "$SEEN")
  case "$stale_at" in ''|*[!0-9]*) stale_at=0 ;; esac
  printf '%s' "$stale_at"
}

emit_stale() {
  local now
  now=$(date +%s)
  [ $((now - $(seen_stale_at))) -ge "${FM_PIPELINE_WATCH_STALE_SECS:-3600}" ] || return 0
  write_seen "$now" "$(seen_keys)"
  echo "pipeline-watch-stale: $PIPELINE $1 $URL"
}

# failures_tsv: read GetPipelineDetails JSON on stdin and print one
# "<key>\t<label>" line per failure. Fails when the body holds no pipeline data.
failures_tsv() {
  jq -r '
    def flat: tostring | gsub("[\t\r\n]+"; " ");
    def step($kind):
      "\($kind) \(.stageName)/\(.stepName // .targetName // .description)" as $label
      | [(if (.url // "") == "" then $label else .url end), $label];
    .content.data as $d
    | if ($d.failuresSummary | type) != "object" then error("no pipeline data") else . end
    | (($d.failuresSummary.builds // [])[] | step("build")),
      (($d.failuresSummary.deployments // [])[] | step("deploy")),
      (($d.failuresSummary.tests // [])[] | step("test")),
      (($d.promotionSummary.blockedPromotions // [])[] as $p
       | ($p.promotionBlockers // [])[] | select(.type != "TIME_WINDOW")
       | ["promotion:\($p.id):\(.name)",
          "blocked \($p.sourceTarget.name)->\($p.destinationTarget.name) by \(.name)"])
    | map(flat) | @tsv'
}

action_poll() {
  local builder timeout payload errfile raw rc=0 stderr_line='' err items keys prev new labels
  builder=${FM_PIPELINE_WATCH_BUILDER:-$SCRIPT_DIR/fm-builder-mcp-call.sh}
  timeout=${FM_PIPELINE_WATCH_TIMEOUT:-20}
  mkdir -p "$STATE" || return 1
  if [ ! -x "$builder" ]; then
    emit_stale "builder CLI not found at $builder (set FM_PIPELINE_WATCH_BUILDER)"
    return 0
  fi
  payload=$(jq -cn --arg p "$PIPELINE" '{pipelineName: $p, includeAllFailures: true}')
  errfile=$(mktemp "$SEEN.err.XXXXXX") || errfile=
  raw=$(fm_run_timed "$timeout" "$builder" GetPipelineDetails "$payload" 2>"${errfile:-/dev/null}") || rc=$?
  if [ -n "$errfile" ]; then
    stderr_line=$(sed -n '/[^[:space:]]/{p;q;}' "$errfile" | cut -c1-200)
    rm -f -- "$errfile"
  fi
  if [ -z "$raw" ]; then
    if fm_timed_out "$rc"; then
      emit_stale "builder read timed out after ${timeout}s"
    elif [ "$rc" = 0 ] && [ -z "$stderr_line" ]; then
      emit_stale "builder returned no output (run the builder CLI by hand to see why)"
    else
      emit_stale "builder read failed (rc=$rc)${stderr_line:+: $stderr_line}"
    fi
    return 0
  fi
  err=$(printf '%s' "$raw" | jq -r '.content.errors[0]? // empty | tostring' 2>/dev/null) || err=
  if [ -n "$err" ]; then
    emit_stale "builder error: $(printf '%s' "$err" | tr '\n' ' ')"
    return 0
  fi
  if [ "$rc" -ne 0 ]; then
    emit_stale "builder read failed (rc=$rc)${stderr_line:+: $stderr_line}"
    return 0
  fi
  if ! items=$(printf '%s' "$raw" | failures_tsv 2>/dev/null); then
    emit_stale "unparsable builder output"
    return 0
  fi

  keys=$(printf '%s\n' "$items" | cut -f1 | sed '/^$/d' | LC_ALL=C sort -u)
  prev=$(seen_keys | LC_ALL=C sort -u)
  new=$(printf '%s\n' "$keys" | LC_ALL=C comm -13 <(printf '%s\n' "$prev") - | sed '/^$/d')
  write_seen "$(seen_stale_at)" "$keys"
  if [ -n "$new" ]; then
    labels=$(printf '%s\n' "$items" | cut -f2 | awk 'NF { printf "%s%s", sep, $0; sep = "; " }')
    echo "pipeline-failing: $PIPELINE $labels $URL"
  elif [ -z "$keys" ] && [ -n "$prev" ]; then
    echo "pipeline-recovered: $PIPELINE $URL"
  fi
}

case "${1:-}" in
  arm)
    [ "$#" -eq 1 ] || die_usage
    action_arm
    ;;
  poll)
    [ "$#" -eq 2 ] || die_usage
    require_pipeline "$2"
    PIPELINE=$2
    SEEN="$STATE/pw-$PIPELINE.seen"
    URL="https://pipelines.amazon.com/pipelines/$PIPELINE"
    action_poll
    ;;
  disarm)
    [ "$#" -le 2 ] || die_usage
    action_disarm "${2:-}"
    ;;
  -h|--help) usage ;;
  *) die_usage ;;
esac
